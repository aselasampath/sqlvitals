using System.Text;
using SqlVitals.Engine.Scripting;

namespace SqlVitals.Engine.Security;

/// <summary>How much a finding matters. Risks sort first.</summary>
public enum SecurityFindingStatus
{
    /// <summary>Widens the attack surface: fix it unless there's a reason not to.</summary>
    Risk,

    /// <summary>Not wrong in itself, but worth a look: someone should know why it's there.</summary>
    Review,

    /// <summary>Couldn't be checked here: a permission is missing, or the database couldn't be read.</summary>
    NotChecked,

    Pass,
}

/// <summary>What is audited, in the order the page lists them.</summary>
public enum SecurityCheckKind
{
    SaLogin,
    SysadminMember,
    Trustworthy,
    OrphanedUser,
}

/// <summary>
/// One row of the security audit (#43): a login, database or user, what was found, and the risk
/// it carries.
/// </summary>
/// <param name="Scope">"Server", a database's name, or "All 12 databases" for the ones that pass.</param>
/// <param name="Subject">The login, database or user the finding is about.</param>
/// <param name="Finding">What was found, in a few words: "SQL login · enabled".</param>
/// <param name="Explanation">Why it matters: the risk, or why it's fine.</param>
/// <param name="FixScript">T-SQL that would remove the risk. Never run by SqlVitals.</param>
public sealed record SecurityFinding(
    SecurityCheckKind     Kind,
    string                Scope,
    string                Subject,
    SecurityFindingStatus Status,
    string                Finding,
    string                Explanation,
    string?               FixScript = null)
{
    public const string ServerScope = "Server";

    public string Name => NameOf(Kind);

    public static string NameOf(SecurityCheckKind kind) => kind switch
    {
        SecurityCheckKind.SaLogin        => "sa login",
        SecurityCheckKind.SysadminMember => "sysadmin member",
        SecurityCheckKind.Trustworthy    => "TRUSTWORTHY",
        SecurityCheckKind.OrphanedUser   => "Orphaned user",
        _                                => kind.ToString(),
    };

    public bool IsRisk => Status == SecurityFindingStatus.Risk;

    public string StatusText => Status switch
    {
        SecurityFindingStatus.Risk   => "Risk",
        SecurityFindingStatus.Review => "Review",
        SecurityFindingStatus.Pass   => "Pass",
        _                            => "Not checked",
    };
}

/// <summary>The audit of one server, risks first, or why it couldn't be read.</summary>
/// <param name="Problem">Something that left checks out, or why the list is empty.</param>
public sealed record SecurityFindingList(IReadOnlyList<SecurityFinding> Findings, string? Problem)
{
    /// <summary>False when nothing could be read.</summary>
    public bool Available { get; init; } = true;

    public static SecurityFindingList Unavailable(string problem) => new([], problem) { Available = false };

    public int RiskCount       => Findings.Count(f => f.Status == SecurityFindingStatus.Risk);
    public int ReviewCount     => Findings.Count(f => f.Status == SecurityFindingStatus.Review);
    public int PassCount       => Findings.Count(f => f.Status == SecurityFindingStatus.Pass);
    public int NotCheckedCount => Findings.Count(f => f.Status == SecurityFindingStatus.NotChecked);

    /// <summary>Risks first, then to review, not checked and passed; in the order of <see cref="SecurityCheckKind"/> within each.</summary>
    public static IReadOnlyList<SecurityFinding> Sort(IEnumerable<SecurityFinding> findings) => findings
        .OrderBy(f => f.Status)
        .ThenBy(f => f.Kind)
        .ToList();

    /// <summary>Every risk's fix in one script, for review. Null when there's nothing to fix.</summary>
    public string? FixScript(string server, DateTime now)
    {
        var fixes = Findings.Where(f => f.IsRisk && f.FixScript is not null).ToList();
        if (fixes.Count == 0)
            return null;

        var sb = new StringBuilder();
        sb.AppendLine(ScriptText.Comment($"Security fixes for {server}, generated by SqlVitals on {now:yyyy-MM-dd HH:mm}."));
        sb.AppendLine("-- Review each change before running it: removing access can stop an application or a person from working.");
        sb.AppendLine("-- SqlVitals does not run this script.");
        foreach (var finding in fixes)
        {
            sb.AppendLine();
            sb.AppendLine(ScriptText.Comment($"{finding.Name}: {finding.Subject} ({finding.Scope}): {finding.Finding}"));
            sb.AppendLine(finding.FixScript!.TrimEnd());
            sb.AppendLine("GO");
        }
        return sb.ToString();
    }
}
